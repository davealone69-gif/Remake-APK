package com.example.omni.domain.agent

import com.example.omni.domain.model.ProposedFileChange
import com.example.omni.domain.model.SwarmAgentProposal
import com.example.omni.domain.model.SwarmAgentRole
import com.example.omni.domain.model.MutationStatus
import java.util.UUID

interface SwarmAgent {
    val role: SwarmAgentRole
    suspend fun analyzeAndPropose(
        projectId: String,
        userPrompt: String,
        currentFiles: Map<String, String>,
        apiKey: String
    ): SwarmAgentProposal
}

class ArchitectAgent : SwarmAgent {
    override val role = SwarmAgentRole.ARCHITECT

    override suspend fun analyzeAndPropose(
        projectId: String,
        userPrompt: String,
        currentFiles: Map<String, String>,
        apiKey: String
    ): SwarmAgentProposal {
        val proposalId = "prop-arch-" + UUID.randomUUID().toString()
        val appModulePath = "app/src/main/java/com/example/app/AppModule.kt"
        val existingContent = currentFiles[appModulePath] ?: "// Module placeholder"

        val updatedContent = """
            // Architectural blueprint generated by ArchitectAgent
            package com.example.app

            class AppModule {
                val moduleName = "SwarmArchitectModule"
                val activeTarget = "Android Native (Kotlin/Compose)"

                fun executeTaskBlueprint() {
                    // Plan derived from: $userPrompt
                    println("ArchitectAgent Blueprint initialized for task: $userPrompt")
                }
            }
        """.trimIndent()

        return SwarmAgentProposal(
            id = proposalId,
            projectId = projectId,
            role = role,
            title = "Architectural Blueprint for: ${userPrompt.take(30)}...",
            description = "Structural design and component architecture proposal targeting Android Native Compose & Room state persistence.",
            rationale = "Maintains high separation of concerns, MVVM pattern, and thread-safe Flow data streams.",
            proposedFiles = listOf(
                ProposedFileChange(
                    filePath = appModulePath,
                    oldContent = existingContent,
                    newContent = updatedContent,
                    changeSummary = "Added blueprint module configuration for prompt: $userPrompt"
                )
            ),
            status = MutationStatus.PENDING_APPROVAL
        )
    }
}

